package mapping

import (
	"bytes"
	"fmt"

	"gopkg.in/yaml.v3"

	"github.com/RainerGewalt/trailsource/internal/inventory"
)

// Skeleton renders a mapping file with one exact-path rule per browsed node
// and the derived role filled in. It is a starting point: an integrator
// renames roles, adds units, scaling and context flags, and deletes rules for
// nodes that need nothing (those keep a derived role at runtime anyway).
func Skeleton(items []inventory.Item, source, generatedAt string) ([]byte, error) {
	rules := &yaml.Node{Kind: yaml.SequenceNode}
	for _, it := range items {
		access := "r"
		if it.UserWritable {
			access = "rw"
		}
		rule := &yaml.Node{Kind: yaml.MappingNode}
		pathKey := scalar("path")
		pathVal := scalar(it.BrowsePath)
		pathVal.LineComment = fmt.Sprintf("%s, %s, %s", it.DataType, access, it.NodeID)
		rule.Content = append(rule.Content, pathKey, pathVal, scalar("semantic_role"), scalar(DerivedRole(it.BrowsePath, it.BrowseName)))
		rules.Content = append(rules.Content, rule)
	}
	doc := &yaml.Node{Kind: yaml.MappingNode}
	version := scalar("1")
	version.Style = yaml.DoubleQuotedStyle
	doc.Content = append(doc.Content,
		scalar("version"), version,
		scalar("description"), scalar("Generated from the first browse of "+source),
		scalar("rules"), rules)
	doc.HeadComment = fmt.Sprintf(`Mapping skeleton generated by trailsource browse on %s
from %s (%d nodes).
Edit before use: rename semantic_role, add unit (UN/CEFACT Rec. 20 code),
scale_decimals for PLC-style scaled integers and context: true for recipe,
order or batch variables. Replace groups of exact paths with one pattern
rule where a '*' per browse-path segment fits. Bump version on every change;
the file hash travels in every record as context.mapping.hash.`, generatedAt, source, len(items))
	var buf bytes.Buffer
	enc := yaml.NewEncoder(&buf)
	enc.SetIndent(2)
	if err := enc.Encode(&yaml.Node{Kind: yaml.DocumentNode, Content: []*yaml.Node{doc}}); err != nil {
		return nil, err
	}
	if err := enc.Close(); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}

func scalar(v string) *yaml.Node {
	return &yaml.Node{Kind: yaml.ScalarNode, Tag: "!!str", Value: v}
}
